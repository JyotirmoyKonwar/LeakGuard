"""Turn benchmark records into docs/failure_analysis.md: where each system leaks, over-blocks and why.

Examples are shown with gold values masked as [ENTITY], so the report never re-publishes raw PII/secrets.
    python -m leakguard.eval.failure_analysis --split test
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def masked(text: str, spans: list[dict], limit: int = 220) -> str:
    out, last = [], 0
    for s in sorted(spans, key=lambda s: s["start"]):
        if s["start"] < last:
            continue
        out += [text[last:s["start"]], f"[{s['entity']}]"]
        last = s["end"]
    out.append(text[last:])
    t = "".join(out).replace("\n", " ⏎ ").replace("|", "¦")
    return t[:limit] + ("…" if len(t) > limit else "")


def analyse(split: str, results_dir: Path, data_dir: Path) -> str:
    data = {json.loads(line)["id"]: json.loads(line) for line in (data_dir / f"{split}.jsonl").open()}
    summary = json.loads((results_dir / f"summary_{split}.json").read_text())
    md = [f"# Failure analysis ({split} split)", "",
          "Generated by `python -m leakguard.eval.failure_analysis`. Gold values in the examples are masked as `[ENTITY]`.", ""]
    for system in summary["systems"]:
        path = results_dir / f"records_{split}_{system}.jsonl"
        if not path.exists():
            continue
        recs = [json.loads(line) for line in path.open()]
        s = summary["systems"][system]
        md += [f"## {system}", "",
               f"Leakage recall **{s.get('leakage_recall')}** · false-block rate **{s.get('false_block_rate')}** · "
               f"action accuracy **{s.get('action_accuracy')}** · n={s['n']}", ""]

        # 1) leaks: which entities slip through, in which languages
        missed = Counter(m["entity"] for r in recs for m in r["missed"])
        by_lang: dict[str, Counter] = defaultdict(Counter)
        for r in recs:
            for m in r["missed"]:
                by_lang[r["lang"]][m["entity"]] += 1
        md += ["### Missed entities (not detected at all)", "", "| Entity | Missed | Recall |", "|---|---|---|"]
        for e, n in missed.most_common(10):
            md.append(f"| {e} | {n} | {s['entity_recall'].get(e, {}).get('recall', '–')} |")
        md += ["", "Top miss per language: " + ", ".join(f"{lg}: {c.most_common(1)[0][0]} ({c.most_common(1)[0][1]})"
                                                       for lg, c in sorted(by_lang.items()) if c), ""]

        # 2) false blocks: benign items we stopped, grouped by scenario and the entity that triggered it
        fb = [r for r in recs if r["gold_action"] == "allow" and r["final"] in ("block", "escalate")]
        trig = Counter(fp["entity"] + ("" if not fp.get("source") else f" ({fp['source']})") for r in fb for fp in r["false_pos"])
        md += [f"### False blocks ({len(fb)})", "", "By scenario: " + ", ".join(f"{k} {v}" for k, v in Counter(r['scenario'] for r in fb).most_common()),
               "", "Triggered by: " + (", ".join(f"{k} ×{v}" for k, v in trig.most_common(8)) or "intent / policy only"), ""]
        if any(r.get("codes") for r in fb):
            md.append("Agent reason codes on false blocks: " + ", ".join(
                f"{k} ×{v}" for k, v in Counter(c for r in fb for c in r.get("codes", [])).most_common()) + "")
            md.append("")

        # 3) wrong actions on items that needed protection
        under = [r for r in recs if r["gold_protect"] and r["final"] == "allow"]
        md += [f"### Under-protection: gold says intervene, system allowed ({len(under)})", "",
               "By scenario: " + ", ".join(f"{k} {v}" for k, v in Counter(r['scenario'] for r in under).most_common()), ""]

        # 4) examples
        md += ["### Examples", "", "| Kind | Scenario | Gold → Pred | Text (gold masked) |", "|---|---|---|---|"]
        shown = 0
        for kind, group in (("leak", [r for r in recs if r["leaked_n"]]), ("false block", fb), ("under-protect", under)):
            for r in group[:4]:
                ex = data.get(r["id"])
                if ex:
                    md.append(f"| {kind} | {r['scenario']} | {r['gold_action']} → {r['final']} | {masked(ex['text'], ex['spans'])} |")
                    shown += 1
        if not shown:
            md.append("| – | – | – | no failures |")
        md.append("")

        if system == "agent":
            codes = Counter(c for r in recs for c in r.get("codes", []))
            md += ["### Agent behaviour", "", "Reason codes used: " + (", ".join(f"{k} ×{v}" for k, v in codes.most_common()) or "none"), ""]
            wrong = [r for r in recs if r["gold_action"] in ("allow", "redact", "escalate", "block") and r["final"] != r["gold_action"] and r.get("laya")]
            if wrong:
                buckets = Counter(min(4, int(r["laya"]["confidence"] * 5)) for r in wrong)
                md.append("Laya confidence on wrong decisions: " + ", ".join(
                    f"{b / 5:.1f}–{(b + 1) / 5:.1f}: {buckets[b]}" for b in range(5)))
                md.append("")
    return "\n".join(md) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", default="test")
    ap.add_argument("--results", default=str(ROOT / "eval" / "results"))
    ap.add_argument("--data", default=str(ROOT / "data" / "processed"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "failure_analysis.md"))
    a = ap.parse_args()
    Path(a.out).write_text(analyse(a.split, Path(a.results), Path(a.data)))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
